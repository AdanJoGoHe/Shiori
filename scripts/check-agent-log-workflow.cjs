// Only the disposable deployments created by check-agent-log-workflow.py.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const input=JSON.parse(fs.readFileSync(0,'utf8'));
async function main(){
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'Pacific/Honolulu',permissions:['clipboard-read','clipboard-write']});
  const page=await context.newPage(),errors=[],external=[],checks=[];
  page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(!r.url().startsWith(input.url))external.push(r.url());});
  const idle=()=>page.waitForFunction(()=>!document.getElementById('log-message').textContent.includes('Leyendo')&&document.getElementById('log-list').getAttribute('aria-busy')==='false');
  const post=async(route,data)=>page.request.post(input.url+route,{data,headers:{Origin:new URL(input.url).origin}});
  const get=async(route)=>(await page.request.get(input.url+route)).json();
  await page.goto(input.url+'#agent-log');await page.locator('.log-event').first().waitFor();await idle();
  assert.equal(await page.locator('#view').inputValue(),'agent-log');
  assert.match(await page.locator('#log-activation').innerText(),/desactivado/);
  await page.getByRole('button',{name:'Activar registro',exact:true}).click();await idle();
  assert.match(await page.locator('#log-activation').innerText(),/activado/);
  const cfg=await get('api/agent-log');assert.equal(cfg.enabled,true);
  checks.push('opt-in-profile-activation-and-read-while-disabled');
  await page.locator('#search').fill('describe');await page.waitForFunction(()=>document.querySelectorAll('.log-event').length===1);await idle();
  assert.match(await page.locator('.log-event').innerText(),/Comando ejecutado/);
  await page.locator('.log-event').getByRole('button',{name:'Copiar comando',exact:true}).click();
  await page.waitForFunction(()=>document.getElementById('log-message').textContent.includes('copiado'));
  assert.equal((await page.evaluate(()=>navigator.clipboard.readText())).replace(/\r\n/g,'\n'),input.command);
  await page.locator('.log-event').getByRole('button',{name:'Ver acción',exact:true}).click();
  await page.locator('#log-detail pre').waitFor();
  assert.equal(await page.locator('#log-detail pre code').innerText(),input.command);
  assert.match(await page.locator('#log-detail').innerText(),/Referencia no disponible/);
  const anchor=page.locator('#log-detail a');assert.equal(await anchor.getAttribute('rel'),'noopener noreferrer');
  const guide=page.locator('.log-reference').filter({hasText:'Guía del ejemplo'});
  await guide.getByRole('button',{name:'Abrir página',exact:true}).click();await page.locator('#reader-body').getByText(/Documento ficticio/).waitFor();
  await page.locator('#back').click();await page.locator('#log-detail pre').waitFor();await idle();
  assert.equal(await page.locator('#search').inputValue(),'describe');
  assert.equal(await page.locator('#log-detail pre code').innerText(),input.command);
  checks.push('exact-multiline-copy-authorized-inert-references-reader-and-back');
  await page.locator('.log-reference').filter({hasText:'Avance del diario'}).getByRole('button',{name:'Abrir día del avance'}).click();
  await page.locator('#reader-body').getByText(/Se revisó el recorrido/).waitFor();await page.locator('#back').click();await page.locator('#log-detail pre').waitFor();
  await page.locator('#log-clear').click();await idle();
  await page.locator('#log-kind').selectOption('link-found');await page.locator('#log-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();
  assert.equal(await page.locator('.log-event').count(),1);assert.match(await page.locator('.log-event').innerText(),/Enlace encontrado/);
  await page.locator('#log-kind').selectOption('page-visited');await page.locator('#log-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();
  assert.match(await page.locator('.log-event').innerText(),/Página visitada/);
  await page.locator('#log-clear').click();await idle();await page.locator('#log-yesterday').click();await idle();
  assert.equal(await page.locator('.log-event').count(),1);assert.match(await page.locator('.log-event').innerText(),/ayer/);
  await page.locator('#log-today').click();await idle();
  await page.locator('#log-next').click();await idle();assert.match(await page.locator('#log-page').innerText(),/2/);
  await page.locator('#log-prev').click();await idle();assert.match(await page.locator('#log-page').innerText(),/1/);
  checks.push('day-session-kind-outcome-filters-paging-and-journal-links');
  const before=await get('api/agent-log');await post('api/agent-log/config',{enabled:false,revision:before.revision});
  await page.locator('#log-toggle').click();await page.waitForFunction(()=>document.getElementById('log-message').textContent.includes('cambió'));
  await page.locator('#refresh').click();await idle();assert.match(await page.locator('#log-activation').innerText(),/desactivado/);
  await page.locator('#log-toggle').click();await idle();
  const current=(await get('api/agent-log?event_id=command-demo')).item;
  const denied=await post('api/agent-log',{...current,recorded_at:undefined,scope:input.scope==='personal'?'work':'personal',event_id:'wrong-profile'});assert.equal(denied.status(),400);
  checks.push('concurrent-activation-conflict-and-cross-profile-rejection');
  await page.locator('#log-session').fill('session-main');await page.locator('#log-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();
  await page.locator('.log-event[data-event-id="command-demo"]').getByRole('button',{name:'Ver acción',exact:true}).click();await page.locator('#log-detail pre').waitFor();
  for(const width of [1280,1440,1920,720])for(const theme of ['light','dark','latte']){
    await page.setViewportSize({width,height:1000});await page.locator('#theme').selectOption(theme);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(input.screenshots,`${input.scope}-${width}-${theme}.png`),fullPage:true});
  }
  checks.push('three-desktop-widths-themes-and-zoom-without-overflow');
  await page.locator('#log-session').fill('unknown-session');await page.locator('#log-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();assert.match(await page.locator('#log-list').innerText(),/Sin acciones registradas/);
  await page.route('**/api/agent-log?*',r=>r.abort());await page.locator('#refresh').click();await page.waitForFunction(()=>document.getElementById('log-message').textContent.includes('No se pudo leer'));
  await page.unroute('**/api/agent-log?*');await page.locator('#log-clear').click();await idle();
  await page.locator('[data-screen="diario"]').click();await page.locator('#journal-count').getByText(/capturas/).waitFor();
  await page.locator('.journal-entry[data-event-id="agent-log-day"]').getByRole('button',{name:'Ver acciones asociadas'}).click();await idle();
  assert.equal(await page.locator('#log-journal-event').inputValue(),'agent-log-day');
  assert.equal(await page.locator('.log-event').count(),1);
  checks.push('empty-error-retry-and-diary-to-associated-actions');
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  await browser.close();console.log(JSON.stringify({scope:input.scope,checks}));
}
main().catch(e=>{console.error(e);process.exit(1)});
