// Only disposable profiles created by check-favorites-workflow.py.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const input=JSON.parse(fs.readFileSync(0,'utf8'));
async function main(){
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[],external=[],checks=[];
  page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(input.url))external.push(r.url());});
  const idle=()=>page.waitForFunction(()=>document.getElementById('favorite-list').getAttribute('aria-busy')==='false'&&!document.getElementById('favorite-status').textContent.includes('Leyendo'));
  const get=async(route)=>(await page.request.get(input.url+route)).json();
  const post=async(data)=>(await page.request.post(input.url+'api/favorites',{data,headers:{Origin:new URL(input.url).origin}})).json();
  const target='documentation:demo:guide.md';
  await page.goto(input.url+'#favoritos');await idle();
  assert.match(await page.locator('#favorite-list').innerText(),/No hay favoritos/);
  await page.keyboard.press('Control+k');assert.equal(await page.locator('#search').evaluate(el=>el===document.activeElement),true);
  await page.locator('[data-screen="biblioteca"]').click();await page.locator('.result').first().waitFor();
  await page.locator('.page-result-row').first().getByRole('button',{name:'Añadir a favoritos',exact:true}).click();
  await page.locator('.page-result-row').first().getByRole('button',{name:'Quitar de favoritos',exact:true}).waitFor();
  await page.locator('.result').first().click();await page.locator('#reader-favorite').getByRole('button',{name:'Quitar de favoritos',exact:true}).waitFor();
  await page.locator('#reader-favorite').getByRole('button',{name:'Quitar de favoritos',exact:true}).click();
  await page.locator('#reader-favorite').getByRole('button',{name:'Añadir a favoritos',exact:true}).click();
  await page.locator('#reader-favorite').getByRole('button',{name:'Quitar de favoritos',exact:true}).waitFor();
  assert.equal((await get('api/favorites')).total,1);
  checks.push('first-run-keyboard-result-reader-shared-state');
  const second=await context.newPage();await second.goto(input.url+'#biblioteca');await second.locator('.result').first().click();
  await second.locator('#reader-favorite').getByRole('button',{name:'Quitar de favoritos',exact:true}).waitFor();
  await page.locator('[data-screen="favoritos"]').click();await idle();
  await page.getByRole('button',{name:'Editar favorito',exact:true}).click();
  await page.locator('#favorite-title').fill('Comprobaciones del laboratorio');await page.locator('#favorite-edit-tags').fill('comando, windows');
  await page.locator('#favorite-save').click();await page.locator('#favorite-editor').waitFor({state:'hidden'});await idle();
  await second.locator('#reader-favorite').getByRole('button',{name:'Quitar de favoritos',exact:true}).click();
  await second.waitForFunction(()=>document.getElementById('copy-message').textContent.includes('cambió'));
  assert.equal((await get('api/favorites')).total,1);await second.close();
  checks.push('two-tabs-stale-version-rejected-without-removing');
  await page.locator('#search').fill('echo ejemplo');await page.waitForFunction(()=>document.getElementById('favorite-count').textContent==='1 favoritos');await idle();
  await page.locator('#favorite-tags').fill('com');await page.locator('#favorite-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();
  assert.equal(await page.locator('.favorite-row').count(),0);
  await page.locator('#favorite-tags').fill('comando');await page.locator('#favorite-filter-form').getByRole('button',{name:'Aplicar filtros'}).click();await idle();
  await page.getByRole('button',{name:'Abrir página',exact:true}).click();await page.locator('#reader-body').getByText(/echo ejemplo/).waitFor();
  await page.locator('#back').click();await page.locator('#favorites-panel').waitFor();await idle();
  assert.equal(await page.locator('#favorite-tags').inputValue(),'comando');assert.equal(await page.locator('#search').inputValue(),'echo ejemplo');
  checks.push('authorized-content-search-exact-tags-reader-and-back');
  await page.locator('#clear').click();await idle();await page.locator('#favorite-add').click();
  await page.locator('#favorite-target').fill('https://example.test/commands');await page.locator('#favorite-title').fill('Manual de comandos');await page.locator('#favorite-save').click();
  await page.locator('#favorite-editor').waitFor({state:'hidden'});await idle();
  const web=page.locator('.favorite-row').filter({hasText:'Manual de comandos'});
  assert.equal(await web.getByRole('link',{name:'Abrir enlace'}).getAttribute('rel'),'noopener noreferrer');
  assert.equal((await get('api/favorites?kind=web')).items[0].excerpt,'');
  await page.locator('[data-screen="agent-log"]').click();await page.locator('.log-reference').waitFor();
  await page.locator('.log-reference').getByRole('button',{name:'Añadir a favoritos',exact:true}).click();
  await page.locator('.log-reference').getByRole('button',{name:'Quitar de favoritos',exact:true}).waitFor();
  assert.equal((await get('api/favorites?target='+encodeURIComponent('https://example.test/log-guide'))).total,1);
  checks.push('reviewed-web-form-and-agent-log-handoff-without-fetch');
  fs.renameSync(input.guide,input.guide+'.renamed.md');
  await page.locator('[data-screen="favoritos"]').click();await idle();
  const broken=page.locator('.favorite-row').filter({hasText:'Comprobaciones del laboratorio'});
  assert.match(await broken.innerText(),/No disponible/);assert.equal(await broken.getByRole('button',{name:'Abrir página'}).count(),0);
  await broken.getByRole('button',{name:'Reparar favorito'}).click();
  await page.locator('#favorite-target').fill(target+'.renamed.md');await page.locator('#favorite-save').click();
  await page.locator('#favorite-editor').waitFor({state:'hidden'});await idle();
  assert.equal((await get('api/favorites?target='+encodeURIComponent(target))).total,0);
  await page.reload();await idle();assert.equal((await get('api/favorites')).total,3);
  checks.push('unavailable-does-not-guess-explicit-repair-and-reload');
  await page.locator('[data-screen="inicio"]').click();await page.locator('#home-favorites .favorite-row').first().waitFor();
  assert.equal(await page.locator('#home-favorites .favorite-row').count(),3);
  await page.locator('#home-favorites').getByRole('button',{name:'Abrir página',exact:true}).click();await page.locator('#reader-body').getByText(/echo ejemplo/).waitFor();
  await page.locator('#back').click();await page.locator('#home-panel').waitFor();
  await page.locator('[data-screen="favoritos"]').click();await idle();
  for(let i=0;i<22;i++)await post({target:'https://example.test/page/'+i,title:'Referencia '+i,project:'demo',tags:['paginacion'],version:0});
  await page.locator('#refresh').click();await idle();
  await page.locator('#favorite-next').click();await idle();assert.match(await page.locator('#favorite-page').innerText(),/2/);
  await page.locator('#favorite-prev').click();await idle();
  await page.route('**/api/favorites?**',route=>route.fulfill({status:500,contentType:'application/json',body:'{"error":"Fallo de prueba"}'}));
  await page.locator('#refresh').click();await page.waitForFunction(()=>document.getElementById('favorite-status').textContent.includes('No se pudieron'));
  await page.unroute('**/api/favorites?**');await page.locator('#refresh').click();await idle();
  checks.push('home-reader-return-server-pagination-and-retry');
  for(const theme of ['light','dark','latte'])for(const width of [1280,1440,1920,720]){
    await page.setViewportSize({width,height:1000});await page.locator('#theme').selectOption(theme);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
    await page.screenshot({path:path.join(input.screenshots,`${input.scope}-${theme}-${width}.png`),fullPage:true});
  }
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  await browser.close();return {scope:input.scope,checks,themes:3,widths:[1280,1440,1920,720],external_requests:0};
}
main().then(r=>process.stdout.write(JSON.stringify(r))).catch(e=>{console.error(e.stack);process.exit(1)});
