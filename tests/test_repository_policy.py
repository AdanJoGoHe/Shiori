import importlib.util
import subprocess
from pathlib import Path

import pytest


spec = importlib.util.spec_from_file_location(
    "repository_policy", Path(__file__).resolve().parents[1] / "scripts/check-repository.py"
)
policy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(policy)


@pytest.mark.parametrize(
    "name,raw,mode",
    [
        ("docs/guide.md", b"Readable UTF-8 source\n", "100644"),
        ("config/personal.example.json", b"{}\n", "100644"),
        (".githooks/pre-commit", b"#!/bin/sh\n", "100755"),
    ],
)
def test_publishable_text(name, raw, mode):
    assert policy.file_issues(name, raw, mode) == []


@pytest.mark.parametrize(
    "name,raw,mode",
    [
        ("config/personal.json", b"{}", "100644"),
        ("docs/vault/note.md", b"private", "100644"),
        ("docs/image.exe", b"executable", "100644"),
        ("docs/guide.md", b"\xff", "100644"),
        ("docs/guide.md", b"hello\x00world", "100644"),
        ("docs/guide.md", ("hello" + chr(0x202E)).encode(), "100644"),
        ("docs/guide.md", (chr(0xC3) + chr(0xB1)).encode(), "100644"),
        ("docs/guide.md", b"target", "120000"),
        ("docs/guide.md", b"x" * (policy.MAX_BYTES + 1), "100644"),
        ("assets/mark.svg", b"<svg><script>alert(1)</script></svg>", "100644"),
        ("assets/mark.svg", b'<svg><image href="https://example.com/x"/></svg>', "100644"),
    ],
    ids=[
        "config",
        "vault",
        "binary-name",
        "encoding",
        "nul",
        "bidi",
        "mojibake",
        "symlink",
        "oversize",
        "active-svg",
        "external-svg",
    ],
)
def test_rejects_unreviewed_content_without_echoing_it(name, raw, mode):
    issues = policy.file_issues(name, raw, mode)
    assert issues
    assert "alert(1)" not in " ".join(issues)


def test_personal_user_paths_need_placeholders():
    prefix = "C:" + "/Users/"
    assert policy.file_issues("docs/guide.md", (prefix + "alice/config.json").encode())
    assert not policy.file_issues("docs/guide.md", (prefix + "USER/config.json").encode())


def test_message_checks_body_and_case():
    assert not policy.message_issues("fix: preserve memory during upgrades")
    for text in ["CoDeX: change", "fix: improve retrieval\n\nGenerated by " + "CODEX"]:
        assert policy.message_issues(text)


def test_staged_scan_uses_index_not_working_tree(tmp_path):
    subprocess.run(["git", "init", str(tmp_path)], check=True, capture_output=True)
    readme = tmp_path / "README.md"
    readme.write_text("staged content\n", encoding="utf-8")
    subprocess.run(["git", "add", "README.md"], cwd=tmp_path, check=True)
    readme.write_bytes(b"working\x00content")
    staged = list(policy.source_files(tmp_path, staged=True))
    working = list(policy.source_files(tmp_path, staged=False))
    assert staged[0][2] == b"staged content\n"
    assert not policy.file_issues(*[staged[0][0], staged[0][2], staged[0][1]])
    assert policy.file_issues(*[working[0][0], working[0][2], working[0][1]])
